if __name__ == '__main__':
    import sys
    sys.path.insert(0, str(R / 'grading'))
    from scorer import costs_from_roster, GRADER_VERSION
    costs = costs_from_roster(json.loads((R / 'organization/roster.json').read_text(encoding='utf-8')))
    n = 0
    for d in sorted((R / 'templates').iterdir()):
        bp = json.loads((d / 'blueprint.json').read_text(encoding='utf-8'))
        g = d / 'tac' / 'grading'; g.mkdir(parents=True, exist_ok=True)
        (g / 'blueprint_private.json').write_text(json.dumps(bp, ensure_ascii=False, indent=2), encoding='utf-8')
        (g / 'costs.json').write_text(json.dumps({k: costs[k] for k in bp['candidate_pool']}, indent=2), encoding='utf-8')
        shutil.copy(R / 'grading' / 'scorer.py', g / 'scorer.py')
        (d / 'tac' / 'evaluator.py').write_text(TAC_EVALUATOR.format(task_id=bp['task_id'], version=GRADER_VERSION), encoding='utf-8')
        bp['output_contract']['grading_implemented'] = True
        bp['output_contract']['grader'] = {'version': GRADER_VERSION, 'module': 'grading/scorer.py', 'tac_entry': 'tac/evaluator.py'}
        (d / 'blueprint.json').write_text(json.dumps(bp, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        n += 1
    (R / 'grading' / 'run_local.py').write_text(LOCAL_RUNNER, encoding='utf-8')
    print('entry points written for', n, 'tasks')
