"""Authenticated OpenAI-compatible transport for upstream Sotopia -> Anthropic.
No NPC policy logic here. Responses are generated by the selected real LLM.
"""
import os,json,time,threading
from pathlib import Path
from http.server import ThreadingHTTPServer,BaseHTTPRequestHandler
import anthropic
OUT=Path(os.environ['TAC_RUN_DIR']);OUT.mkdir(parents=True,exist_ok=True)
TOKEN=os.environ['TAC_BRIDGE_TOKEN'];MODEL='claude-haiku-5-5';lock=threading.Lock();cost=0
client=anthropic.Anthropic(max_retries=0,timeout=90)
def log(x):
 with lock:
  with (OUT/'npc_api_io.jsonl').open('a') as f:f.write(json.dumps(x,ensure_ascii=False)+'\n')
class Handler(BaseHTTPRequestHandler):
 def log_message(self,*args):pass
 def do_POST(self):
  global cost
  if self.headers.get('Authorization')!='Bearer '+TOKEN:self.send_error(401);return
  if self.path not in ['/v1/chat/completions','/chat/completions']:self.send_error(404);return
  data=json.loads(self.rfile.read(int(self.headers['Content-Length'])))
  # Sotopia emits chat JSON through an OpenAI-compatible interface, not native tools.
  system='\n'.join(str(m['content']) for m in data['messages'] if m['role']=='system');messages=[m for m in data['messages'] if m['role'] in ['user','assistant']]
  start=time.time()
  try:
   with lock:
    if cost>=.25:raise RuntimeError('NPC estimated cost cap reached')
   response=client.messages.create(model=MODEL,max_tokens=min(int(data.get('max_tokens') or 2048),2048),system=system,messages=messages)
   text=''.join(b.text for b in response.content if b.type=='text');u=response.usage.model_dump();estimated=(u['input_tokens']*.1+u['output_tokens']*.5)/1e6
   with lock:cost+=estimated
   log({'request':data,'response_text':text,'model_returned':response.model,'usage':u,'estimated_cost_usd':estimated,'latency_s':time.time()-start,'stop_reason':response.stop_reason})
   result={'id':response.id,'object':'chat.completion','created':int(time.time()),'model':response.model,'choices':[{'index':0,'message':{'role':'assistant','content':text},'finish_reason':'stop' if response.stop_reason=='end_turn' else 'length'}],'usage':{'prompt_tokens':u['input_tokens'],'completion_tokens':u['output_tokens'],'total_tokens':u['input_tokens']+u['output_tokens']}}
   body=json.dumps(result).encode();self.send_response(200);self.send_header('Content-Type','application/json');self.end_headers();self.wfile.write(body)
  except Exception as exc:
   log({'error_type':type(exc).__name__,'status':getattr(exc,'status_code',None),'latency_s':time.time()-start});self.send_error(502,'LLM request failed; see sanitized audit')
ThreadingHTTPServer(('0.0.0.0',18941),Handler).serve_forever()
